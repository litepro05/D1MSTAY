CREATE TABLE IF NOT EXISTS admin_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(30) NOT NULL UNIQUE,
    rate NUMERIC(14,2) NOT NULL CHECK (rate > 0),
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS resident (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    room_id BIGINT NOT NULL REFERENCES room(id),
    move_in DATE NOT NULL,
    move_out DATE,
    CHECK (move_out IS NULL OR move_out >= move_in)
);

-- Menjamin satu penghuni aktif per kamar, termasuk saat dua permintaan bersamaan.
CREATE UNIQUE INDEX IF NOT EXISTS one_active_resident_per_room
    ON resident(room_id) WHERE move_out IS NULL;

CREATE TABLE IF NOT EXISTS bill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id BIGINT NOT NULL REFERENCES resident(id),
    period VARCHAR(7) NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    due_date DATE NOT NULL,
    paid_on DATE,
    method VARCHAR(10),
    UNIQUE (resident_id, period),
    CHECK ((paid_on IS NULL AND method IS NULL)
        OR (paid_on IS NOT NULL AND method IN ('Tunai', 'Transfer')))
);
